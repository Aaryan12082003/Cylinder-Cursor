import { expect, test } from '@playwright/test'

test('opening stock, dispatch, and partial return update the live balances', async ({ page }) => {
  await page.goto('/#/inventory')
  await page.getByRole('button', { name: 'Set opening balance' }).click()
  const opening = page.getByRole('dialog', { name: 'Opening stock' })
  const filled = opening.getByLabel('Filled')
  await filled.nth(0).fill('100')
  await filled.nth(1).fill('200')
  await filled.nth(2).fill('300')
  await opening.getByRole('button', { name: 'Save opening stock' }).click()
  await expect(opening).toBeHidden()
  await expect(page.getByText('Available').first()).toBeVisible()
  await expect(page.getByText('100', { exact: true }).first()).toBeVisible()

  await page.goto('/#/customers')
  await page.getByRole('button', { name: 'Add customer' }).click()
  const customer = page.getByRole('dialog', { name: 'Add customer' })
  await customer.getByLabel('Party / company name').fill('Customer A')
  await customer.getByRole('textbox', { name: 'Mobile', exact: true }).fill('9845000001')
  await customer.getByRole('button', { name: 'Add customer' }).click()
  await expect(page.getByRole('button', { name: /Customer A/ })).toBeVisible()

  await page.goto('/#/dispatch')
  await page.getByLabel('Customer').selectOption({ label: 'Customer A' })
  await page.getByRole('button', { name: 'Add size' }).click()
  await page.getByRole('button', { name: 'Add size' }).click()
  const sizes = page.locator('select').filter({ hasText: '3 Litre' })
  await sizes.nth(0).selectOption({ label: '3 Litre' })
  await sizes.nth(1).selectOption({ label: '10 Litre' })
  await sizes.nth(2).selectOption({ label: '23 Litre' })
  const quantities = page.getByPlaceholder('Qty')
  await quantities.nth(0).fill('10')
  await quantities.nth(1).fill('20')
  await quantities.nth(2).fill('30')
  await page.getByRole('button', { name: 'Review dispatch' }).click()
  await page.getByRole('button', { name: 'Dispatch' }).click()
  await expect(page.getByText(/DSP-/).first()).toBeVisible()

  await page.goto('/#/returns')
  await page.getByLabel('Customer').selectOption({ label: 'Customer A' })
  await page.getByRole('button', { name: 'Add size' }).click()
  await page.getByRole('button', { name: 'Add size' }).click()
  const returnSizes = page.locator('select').filter({ hasText: '3 Litre' })
  await returnSizes.nth(0).selectOption({ label: '3 Litre' })
  await returnSizes.nth(1).selectOption({ label: '10 Litre' })
  await returnSizes.nth(2).selectOption({ label: '23 Litre' })
  const returnQty = page.getByPlaceholder('Qty')
  await returnQty.nth(0).fill('5')
  await returnQty.nth(1).fill('10')
  await returnQty.nth(2).fill('15')
  for (const box of await page.locator('select').filter({ hasText: 'Empty' }).all()) {
    await box.selectOption('filled')
  }
  await page.getByRole('button', { name: 'Review return' }).click()
  await page.getByRole('button', { name: 'Receive' }).click()
  await expect(page.getByText(/RTN-/).first()).toBeVisible()

  await page.goto('/#/customers')
  await page.getByRole('button', { name: /Customer A/ }).click()
  await expect(page.getByText('Total 30 cylinders')).toBeVisible()

  await page.goto('/#/inventory')
  await expect(page.getByText('95', { exact: true }).first()).toBeVisible()
  await expect(page.getByText('190', { exact: true }).first()).toBeVisible()
  await expect(page.getByText('285', { exact: true }).first()).toBeVisible()
})
